def generated(name="ddl", *, scd2=False, constraints=None, transform=None, columns=None, data=None, grain=None):
    columns = columns or [("event_id", SemanticRole.IDENTIFIER),
                          ("customer_id", SemanticRole.IDENTIFIER),
                          ("amount", SemanticRole.MEASURE)]
    data = data or [["E1", "C1", 10], ["E2", "C2", 20]]
    grain = grain or ["event_id"]
    dataset, _, grain_definition, ids, dimensional_report = proposal(name, columns, data, grain)
    dimensional = validate_dimensional_discovery(dimensional_report,
        accepted_unresolved_fields=dimensional_report.unresolved_fields)
    report = build_star_schema_contract(dataset, grain_definition, dimensional, constraints or {})
    if transform: transform(report, ids)
    overrides = {}
    if scd2 and report.contract.dimension_tables:
        dim = report.contract.dimension_tables[0]
        overrides[dim.dimension_id] = SCDStrategyContract(
            dimension_id=dim.dimension_id, strategy=SCDType.TYPE_2,
            effective_from_field_plan="effective_from", effective_to_field_plan="effective_to",
            current_flag_plan="is_current", reason="Golden validated SCD2", requires_validation=False)
    validation = validate_star_schema_contract(report, scd_overrides=overrides)
    return dataset, ids, validation, generate_postgresql_ddl(validation)



def test_c_composite_business_key():
    def edit(report, ids):
        bk = report.contract.dimension_tables[0].business_key_fields
        bk.fields = [ids["customer_id"], ids["region_id"]]
        bk.uniqueness_expected = True
    columns = [("event_id", SemanticRole.IDENTIFIER), ("customer_id", SemanticRole.IDENTIFIER),
               ("region_id", SemanticRole.IDENTIFIER), ("amount", SemanticRole.MEASURE)]
    _, _, _, (_, artifact) = generated("composite", transform=edit, columns=columns,
                                       data=[["E1", "C1", "R1", 1]], grain=["event_id"])
    assert "UNIQUE (" in artifact.sql and ", " in artifact.sql.split("UNIQUE (")[1].split(")")[0]



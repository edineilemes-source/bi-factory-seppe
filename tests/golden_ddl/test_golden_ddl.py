def test_j_bridge_only_when_validated():
    def edit(report, _):
        if report.contract.bridge_candidates: report.contract.bridge_candidates[0].requires_validation = False
    cols = [("event_id", SemanticRole.IDENTIFIER), ("person_id", SemanticRole.IDENTIFIER),
            ("group_id", SemanticRole.IDENTIFIER)]
    _, _, _, (plan, _) = generated("bridge", transform=edit, columns=cols,
        data=[["E1", "P1", "G1"], ["E2", "P1", "G2"], ["E3", "P2", "G1"], ["E4", "P2", "G2"]],
        grain=["event_id"])
    _, _, _, (unvalidated, _) = generated("bridge_unvalidated", columns=cols,
        data=[["E1", "P1", "G1"], ["E2", "P1", "G2"], ["E3", "P2", "G1"], ["E4", "P2", "G2"]],
        grain=["event_id"])
    assert sum(t.table_type == "BRIDGE" for t in plan.tables) == 1
    assert not any(t.table_type == "BRIDGE" for t in unvalidated.tables)


